/**
 * Inline icons.
 *
 * The four shapes the site uses (arrow, map pin, menu, close) are drawn with
 * the path data from lucide-react (ISC licence) rather than pulling the whole
 * library in for four SVGs. Every icon is decorative: it inherits the text
 * colour and is hidden from assistive technology, so the accessible name of a
 * control always comes from its text content.
 */
interface IconProps {
  size?: number
  className?: string
}

function Icon({
  size = 16,
  className,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {children}
    </svg>
  )
}

export function ArrowRightIcon(props: IconProps) {
  return (
    <Icon {...props}>
      <path d="M5 12h14" />
      <path d="m12 5 7 7-7 7" />
    </Icon>
  )
}

